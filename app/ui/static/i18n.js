  let current = "de";

  function t(key, vars) {
    const table = DICT[current] || DICT.de;
    let text = table[key] ?? DICT.de[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  }

  function formatNumber(n) {
    return new Intl.NumberFormat(current === "en" ? "en-US" : "de-DE").format(n);
  }

  function formatSeconds(sec) {
    const s = Number(sec).toFixed(1);
    return current === "en" ? s : s.replace(".", ",");
  }

  function applyDom(root = document) {
    document.documentElement.lang = current;
    document.title = t("page.title");
    for (const el of root.querySelectorAll("[data-i18n]")) {
      el.textContent = t(el.dataset.i18n);
    }
    for (const el of root.querySelectorAll("[data-i18n-placeholder]")) {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    }
    for (const el of root.querySelectorAll("[data-i18n-title]")) {
      el.title = t(el.dataset.i18nTitle);
    }
    for (const btn of root.querySelectorAll(".lang-btn")) {
      const active = btn.dataset.lang === current;
      btn.classList.toggle("active", active);
      btn.setAttribute("aria-pressed", String(active));
    }
  }

  function setLang(lang) {
    if (!DICT[lang]) return current;
    current = lang;
    applyDom();
    return current;
  }

  window.TopicTreeI18n = {
    get lang() { return current; },
    setLang,
    t,
    applyDom,
    formatNumber,
    formatSeconds,
  };
